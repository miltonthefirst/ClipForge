// Writes which build this is into the web app, so it can say what version it
// is: the number from the repository's VERSION file (the same one the worker
// and the agent report, see apps/worker/clipforge/version.py), the commit it was
// built from, and when. Runs before every build, serve, test, lint and
// typecheck (apps/web's npm "pre" scripts); the file it writes is generated,
// so it is gitignored. Copied from Sarungano's scripts/stamp-build.mjs.
//
//   node ../../tools/stamp-build.mjs src/app/build-info.ts
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const target = process.argv[2];
if (!target) {
  console.error('usage: node stamp-build.mjs <output .ts file>');
  process.exit(1);
}

const version = readFileSync(resolve(root, 'VERSION'), 'utf8').trim() || '0.0.0';
let commit = null;
try {
  commit = execSync('git rev-parse --short HEAD', { cwd: root, encoding: 'utf8' }).trim() || null;
  // Built from uncommitted changes: the commit alone would claim code it
  // does not contain.
  if (commit && execSync('git status --porcelain', { cwd: root, encoding: 'utf8' }).trim()) commit += '+';
} catch {
  commit = null;
}

const info = { version, commit, builtAt: new Date().toISOString() };
writeFileSync(
  resolve(process.cwd(), target),
  `// Generated by tools/stamp-build.mjs before each build. Do not edit.\n` +
    `export const BUILD = ${JSON.stringify(info, null, 2)} as const;\n`,
);
console.log(`stamped ${target}: ${version}${commit ? ` (${commit})` : ''}`);
