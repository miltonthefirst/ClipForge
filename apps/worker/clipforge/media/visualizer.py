"""Drawing a video for a piece of music, from the music itself (docs/MUSIC-PLAN.md, M4).

A generated track has no pictures, so its video is drawn by ffmpeg on the CPU:
a slowly moving gradient in the series' colours, the music's own waveform with
a soft glow, and the title. Nothing is generated by a model and nothing is a
person, which keeps it inside the "drawn, no faces" rule
(docs/adr/0027-drawn-cartoons-as-the-first-visual-mode.md), and it renders
faster than real time: a three-minute track takes about a minute.

Two shapes from one track:

- **full**: 1920x1080, the whole track, for a normal upload;
- **short**: 1080x1920, the track's strongest stretch (most energy, by RMS), at
  most 59 seconds, faded in and out, for Shorts.

The pieces that decide something are pure (the window, the titles, the command)
and tested without running ffmpeg; :func:`render` is the one that runs it.
"""

from __future__ import annotations

import subprocess
from dataclasses import dataclass
from pathlib import Path

import numpy as np

from clipforge.media.render import RenderError, _is_encoder_init_failure, escape_filter_path

__all__ = [
    "FULL",
    "SHORT",
    "Palette",
    "Shape",
    "VisualSpec",
    "build_ass",
    "build_command",
    "loudness_profile",
    "palette_for",
    "render",
    "strongest_window",
]


@dataclass(frozen=True)
class Shape:
    name: str
    width: int
    height: int
    wave_height: int
    wave_y: int
    bitrate: str


# A gradient and a waveform compress well, and YouTube re-encodes everything:
# these keep a three-minute video near 70 MB rather than 140.
FULL = Shape("full", 1920, 1080, 300, 610, "3M")
SHORT = Shape("short", 1080, 1920, 360, 1180, "4M")

# Loudness the clip itself is normalised to (media/music.py), so a track video
# sits beside a clip in a feed at the same level.
TARGET_LUFS = -14.0
TARGET_TRUE_PEAK = -1.5
FADE_SECONDS = 1.5


@dataclass(frozen=True)
class Palette:
    colors: tuple[str, str, str, str]
    wave: str


_PALETTES = {
    "lo-fi": Palette(("0x1e1530", "0x3d2a54", "0xc06c84", "0xf8b195"), "0xfff1e6"),
    "cinematic": Palette(("0x0b132b", "0x1c2541", "0x3a506b", "0x5bc0be"), "0xf4fbff"),
    "electronic": Palette(("0x10002b", "0x3c096c", "0x7b2cbf", "0xff4ecd"), "0xfdf0ff"),
    "acoustic": Palette(("0x1b4332", "0x2d6a4f", "0x95d5b2", "0xf4d35e"), "0xfffdf2"),
    "hip-hop": Palette(("0x111111", "0x3d2b1f", "0x7f5539", "0xe9c46a"), "0xfff6e0"),
}
_DEFAULT = Palette(("0x101624", "0x23304a", "0x4a6fa5", "0x9ec5fe"), "0xf5f8ff")


def palette_for(series: str | None) -> Palette:
    key = (series or "").strip().lower().replace("lofi", "lo-fi").replace("hiphop", "hip-hop")
    return _PALETTES.get(key, _DEFAULT)


def loudness_profile(path: Path, *, ffmpeg_bin: str = "ffmpeg", rate: int = 8000) -> np.ndarray:
    """The track as mono 16-bit samples at a low rate: enough to find its
    loudest stretch, whatever format the generator wrote."""
    completed = subprocess.run(  # noqa: S603 - argv built here from our own paths
        [
            ffmpeg_bin,
            "-hide_banner",
            "-loglevel",
            "error",
            "-i",
            str(path),
            "-ac",
            "1",
            "-ar",
            str(rate),
            "-f",
            "s16le",
            "-",
        ],
        capture_output=True,
        check=False,
    )
    if completed.returncode != 0:
        raise RenderError(
            f"could not read the track: {completed.stderr.decode(errors='replace')[:300]}"
        )
    return np.frombuffer(completed.stdout, dtype=np.int16).astype(np.float32) / 32768.0


def strongest_window(samples: np.ndarray, rate: int, seconds: float) -> float:
    """Where the `seconds` with the most energy start, on a whole second.

    RMS per second, then the best sum over a sliding window. A track shorter
    than the window starts at zero.
    """
    per_second = int(rate)
    whole = len(samples) // per_second
    window = int(seconds)
    if whole <= window:
        return 0.0
    energy = np.sqrt(np.mean(samples[: whole * per_second].reshape(whole, per_second) ** 2, axis=1))
    sums = np.convolve(energy, np.ones(window), mode="valid")
    return float(int(np.argmax(sums)))


def _ass_text(text: str) -> str:
    return text.replace("\\", "").replace("{", "(").replace("}", ")").replace("\n", " ")


def build_ass(title: str, subtitle: str, footer: str, shape: Shape) -> str:
    """The words on screen, as an ASS file libass draws with the video."""
    scale = shape.width / 1920 if shape.width >= shape.height else shape.width / 1080
    title_size = int(96 * scale) if shape is FULL else 84
    sub_size = int(40 * scale) if shape is FULL else 42
    foot_size = int(30 * scale) if shape is FULL else 32
    margin = 120 if shape is FULL else 80
    title_v = 140 if shape is FULL else 300
    sub_v = title_v + title_size + 34
    return "\n".join(
        [
            "[Script Info]",
            "ScriptType: v4.00+",
            f"PlayResX: {shape.width}",
            f"PlayResY: {shape.height}",
            "WrapStyle: 0",
            "",
            "[V4+ Styles]",
            "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, "
            "BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, "
            "BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding",
            f"Style: Title,Segoe UI,{title_size},&H00FFFFFF,&H00FFFFFF,&H50000000,&H00000000,"
            f"1,0,0,0,100,100,0,0,1,0,6,7,{margin},{margin},{title_v},1",
            f"Style: Sub,Segoe UI,{sub_size},&H30FFFFFF,&H00FFFFFF,&H50000000,&H00000000,"
            f"0,0,0,0,100,100,2,0,1,0,3,7,{margin + 4},{margin},{sub_v},1",
            f"Style: Foot,Segoe UI,{foot_size},&H60FFFFFF,&H00FFFFFF,&H50000000,&H00000000,"
            f"0,0,0,0,100,100,1,0,1,0,2,1,{margin + 4},{margin},70,1",
            "",
            "[Events]",
            "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text",
            f"Dialogue: 0,0:00:00.00,9:59:59.00,Title,,0,0,0,,{{\\fad(800,0)}}{_ass_text(title)}",
            f"Dialogue: 0,0:00:00.00,9:59:59.00,Sub,,0,0,0,,{{\\fad(1200,0)}}{_ass_text(subtitle)}",
            f"Dialogue: 0,0:00:00.00,9:59:59.00,Foot,,0,0,0,,{_ass_text(footer)}",
            "",
        ]
    )


@dataclass(frozen=True)
class VisualSpec:
    audio: Path
    output: Path
    titles: Path
    shape: Shape
    palette: Palette
    start_sec: float
    duration_sec: float
    fade_out: bool = True


def build_command(spec: VisualSpec, *, encoder: str, ffmpeg_bin: str = "ffmpeg") -> list[str]:
    s, p = spec.shape, spec.palette
    duration = f"{spec.duration_sec:.3f}"
    gradient = (
        f"gradients=s={s.width}x{s.height}:c0={p.colors[0]}:c1={p.colors[1]}:c2={p.colors[2]}"
        f":c3={p.colors[3]}:n=4:speed=0.008:duration={duration}:rate=30:type=radial"
    )
    video = (
        f"[0:a]showwaves=s={s.width}x{s.wave_height}:mode=cline:rate=30:colors={p.wave}"
        f":scale=cbrt:draw=full,format=rgba,colorchannelmixer=aa=0.8,split[w1][w2];"
        f"[w2]gblur=sigma=16[wg];"
        f"[1:v][wg]overlay=0:{s.wave_y}[b1];"
        f"[b1][w1]overlay=0:{s.wave_y},vignette=PI/5,"
        f"subtitles='{escape_filter_path(spec.titles)}'[v]"
    )
    fades = [f"afade=t=in:d={FADE_SECONDS}"]
    if spec.fade_out:
        fades.append(
            f"afade=t=out:st={max(spec.duration_sec - FADE_SECONDS, 0):.3f}:d={FADE_SECONDS}"
        )
    audio = f"[0:a]{','.join(fades)},loudnorm=I={TARGET_LUFS}:TP={TARGET_TRUE_PEAK}:LRA=11[a]"
    return [
        ffmpeg_bin,
        "-hide_banner",
        "-loglevel",
        "error",
        "-y",
        "-ss",
        f"{spec.start_sec:.3f}",
        "-t",
        duration,
        "-i",
        str(spec.audio),
        "-f",
        "lavfi",
        "-i",
        gradient,
        "-filter_complex",
        f"{video};{audio}",
        "-map",
        "[v]",
        "-map",
        "[a]",
        "-c:v",
        encoder,
        "-b:v",
        s.bitrate,
        "-c:a",
        "aac",
        "-b:a",
        "192k",
        "-ar",
        "48000",
        "-ac",
        "2",
        "-pix_fmt",
        "yuv420p",
        "-movflags",
        "+faststart",
        "-map_metadata",
        "-1",
        "-t",
        duration,
        str(spec.output),
    ]


def render(spec: VisualSpec, *, encoder: str = "h264_nvenc", ffmpeg_bin: str = "ffmpeg") -> Path:
    """Run ffmpeg; fall back to libx264 when the hardware encoder cannot start."""
    for attempt in (encoder, "libx264"):
        completed = subprocess.run(  # noqa: S603 - argv built here from our own paths
            build_command(spec, encoder=attempt, ffmpeg_bin=ffmpeg_bin),
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            check=False,
        )
        if completed.returncode == 0:
            return spec.output
        if (
            attempt == encoder
            and encoder != "libx264"
            and _is_encoder_init_failure(completed.stderr)
        ):
            continue
        raise RenderError(f"the music video did not render: {completed.stderr.strip()[-400:]}")
    raise RenderError("the music video did not render")
